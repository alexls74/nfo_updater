package version

import "fmt"

// Version и BuildDate подставляются при сборке через -ldflags (см. Makefile).
// Значения по умолчанию — для случая "собрали через голый `go build`
// без Makefile" (например, локальная отладка) — тогда явно видно,
// что это неофициальная сборка, а не тихо "0.0.0" как будто настоящий релиз.
var (
	Version   = "dev"
	BuildDate = "unknown"
)

// String возвращает одну строку с версией и датой сборки.
//
// Формат рассчитан на разбор из shell: второе поле, разделённое пробелами, —
// это номер версии, установочный скрипт берёт его как `awk '{print $2}'`.
// Порядок полей менять нельзя, не поправив скрипт.
func String() string {
	return fmt.Sprintf("nfo_updater %s (built %s)", Version, BuildDate)
}
