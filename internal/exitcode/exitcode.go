// internal/exitcode/exitcode.go
//
// Коды возврата программы.
//
// Вынесены в отдельный пакет, потому что у них три читателя: сам main.go,
// текст справки в нём же и генератор systemd-юнита, которому нужно знать,
// после какого кода перезапуск бесполезен. Четвёртый читатель — установочный
// скрипт — в Go не заглядывает, но сверяется с этим файлом глазами.
//
// Числа входят во внешний интерфейс программы: на них смотрят systemd и
// nfo_updater.sh.
package exitcode

const (
	// OK — сделано. Для --setup означает ещё и "служба не нужна":
	// человек отказался от работы по расписанию.
	OK = 0

	// Error — прогон не удался или команда употреблена неверно.
	// Повторить имеет смысл.
	Error = 1

	// Config — конфиг сломан, отсутствует или не заполнен. Повторять
	// бесполезно, чинится руками; отсюда RestartPreventExitStatus в юните.
	Config = 2

	// Busy — другой экземпляр уже работает. Не ошибка: так выглядит
	// наложение планового прогона на ручной.
	Busy = 3

	// Aborted — мастер настройки прерван человеком. На диске ничего
	// не изменено. Отделён от Error, чтобы установочный скрипт молча
	// сворачивался, а не рапортовал о неудаче в ответ на осознанный отказ.
	Aborted = 4

	// ServiceWanted — мастер настройки завершён, и человек захотел, чтобы
	// программа работала сама по расписанию. Установочному скрипту это
	// говорит, что нужна служба.
	//
	// Отодвинут от остальных намеренно: прочие коды описывают исход
	// работы, а этот — успех плюс факт.
	ServiceWanted = 10
)
